/**
 * Escapes text for HTML. Graph names, labels and IDs come from user files and
 * the Community Library, so they must never be interpreted as markup (the
 * previous version interpolated them raw → script injection).
 */
export function escapeHtml(v: unknown): string {
  return String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

export function buildPDFHtml(graph: GSSGraph, report: RunReport, verdict: VerdictReport | null): string {
  const pools = Object.entries(report.summary.final_values)
    .map(([id, v]) => `<tr><td>${escapeHtml(id)}</td><td>${v.toFixed(2)}</td><td>${(report.summary.min_values[id] ?? 0).toFixed(2)}</td><td>${(report.summary.max_values[id] ?? 0).toFixed(2)}</td></tr>`)
    .join('')
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>GSS Report — ${escapeHtml(graph.name)}</title>
  <style>body{font-family:sans-serif;margin:2rem;color:#111}h1{color:#6366f1}table{border-collapse:collapse;width:100%}th,td{border:1px solid #ccc;padding:6px 10px;text-align:left}th{background:#f0f0f0}@media print{body{margin:0}}</style>
  </head><body>
  <h1>GSS Economy Report</h1>
  <h2>${escapeHtml(graph.name)}</h2>
  <p>Nodes: ${graph.nodes.length} | Ticks: ${report.summary.total_ticks} | Simulated time: ${report.summary.elapsed.toFixed(1)} s</p>
  ${verdict ? `<p><strong>Verdict:</strong> ${escapeHtml(verdict.verdict.state)} | Health: ${verdict.health_score.total.toFixed(0)}/100</p>` : ''}
  <h3>Final Pool Values</h3>
  <table><tr><th>Pool</th><th>Final</th><th>Min</th><th>Max</th></tr>${pools}</table>
  <p style="margin-top:2rem;color:#888;font-size:12px">Generated by GSS v${escapeHtml(APP_VERSION)} — ${escapeHtml(new Date().toLocaleString())}</p>
  </body></html>`
}

export function buildWebShareHtml(graph: GSSGraph, report: RunReport | null): string {
  const nodeList = graph.nodes.map(n => `<li><strong>${escapeHtml(n.label)}</strong> (type ${escapeHtml(n.type)})</li>`).join('')
  const connList = graph.connections.map(c => `<li>${escapeHtml(c.from_node)} → ${escapeHtml(c.to_node)}</li>`).join('')
  const simData  = report
    ? `<h2>Simulation Results</h2><p>Ticks: ${report.summary.total_ticks} | Simulated time: ${report.summary.elapsed.toFixed(1)} s</p><pre>${escapeHtml(JSON.stringify(report.summary.final_values, null, 2))}</pre>`
    : '<p><em>No simulation data.</em></p>'
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>GSS — ${escapeHtml(graph.name)}</title>
  <style>body{font-family:sans-serif;margin:2rem;max-width:900px;color:#e2e8f0;background:#0a0a14}h1,h2{color:#6366f1}pre{background:#1e1e2e;padding:1rem;border-radius:8px;overflow:auto}ul{padding-left:1.5rem}</style>
  </head><body>
  <h1>🎮 GSS — ${escapeHtml(graph.name)}</h1>
  <p>${escapeHtml(graph.description || 'Economy simulation project')}</p>
  <h2>Graph</h2>
  <p>${graph.nodes.length} nodes, ${graph.connections.length} connections</p>
  <ul>${nodeList}</ul>
  <h2>Connections</h2><ul>${connList}</ul>
  ${simData}
  <hr><p style="color:#555;font-size:12px">Exported from GSS v${escapeHtml(APP_VERSION)} — ${escapeHtml(new Date().toLocaleString())}</p>
  </body></html>`
}

/** Prints HTML through a hidden same-document iframe (no popup window needed). */
function printHtml(html: string): void {
  const frame = document.createElement('iframe')
  frame.setAttribute('aria-hidden', 'true')
  frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0'
  // sandbox bez allow-scripts: obsah iframe nesmí spustit žádný skript
  frame.setAttribute('sandbox', 'allow-modals allow-same-origin')
  frame.srcdoc = html
  frame.onload = () => {
    frame.contentWindow?.focus()
    frame.contentWindow?.print()
    setTimeout(() => frame.remove(), 1000)
  }
  document.body.appendChild(frame)
}

interface ExportFormat {
  id: string
  label: string
  ext: string
  pro: boolean
  needsReport?: boolean
  fileName?: () => string
  generate: () => string
}

export function ExportPanel() {
  const graph        = useGraphStore((s) => s.graph)
  const reportA       = useSimulationStore((s) => s.reportA)
  const verdictReport = useSimulationStore((s) => s.verdictReport)
  const isPro  = useLicenseStore((s) => s.license?.isPro ?? false)
  const [status, setStatus] = useState<string | null>(null)
  const [error,  setError]  = useState<string | null>(null)
  const baseName = safeFileBaseName(graph.name)

  const formats: ExportFormat[] = [
    {
      id: 'gss',
      label: '.gss JSON',
      ext: 'gss',
      pro: false,
      generate: () => exportGSSJson(graph),
    },
    {
      id: 'csv',
      label: 'CSV — long format (time, pool, value)',
      ext: 'csv',
      pro: false,
      needsReport: true,
      fileName: () => `${baseName}_long.csv`,
      generate: () => (reportA ? exportCSV(graph, reportA) : ''),
    },
    {
      id: 'csv_report',
      label: 'CSV — wide format (one column per pool)',
      ext: 'csv',
      pro: false,
      needsReport: true,
      fileName: () => `${baseName}_wide.csv`,
      generate: () => (reportA ? reportToCSV(reportA) : ''),
    },
    {
      id: 'csharp',
      label: 'C# / Unity',
      ext: 'cs',
      pro: true,
      // Unity vyžaduje, aby název souboru odpovídal názvu třídy ScriptableObject.
      fileName: () => `${csharpClassName(graph)}.cs`,
      generate: () => exportCSharp(graph),
    },
    {
      id: 'gdscript',
      label: 'GDScript / Godot 4',
      ext: 'gd',
      pro: true,
      generate: () => exportGDScript(graph),
    },
    {
      id: 'typescript',
      label: 'TypeScript / Web',
      ext: 'ts',
      pro: true,
      generate: () => exportTypeScript(graph),
    },
    {
      id: 'diagnostics',
      label: 'Diagnostics Bundle (JSON)',
      ext: 'json',
      pro: false,
      fileName: () => `${baseName}_diagnostics.json`,
      generate: () => {
        const bundle = buildDiagnosticsBundle(
          graph,
          reportA ? [reportA] : [],
          validate(graph),   // aktuální stav grafu, ne výsledek posledního běhu
        )
        return bundleToJSON(bundle)
      },
    },
  ]

  async function saveText(ext: string, fileName: string, content: string) {
    setStatus(null)
    setError(null)
    try {
      const savedName = await platform.saveFile([ext], fileName, content)
      if (savedName) setStatus(`Saved: ${savedName.split(/[\\/]/).pop()}`)
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  async function handleExport(fmt: ExportFormat) {
    if (fmt.pro && !isPro) {
      setError(`${fmt.label} export requires GSS PRO.`)
      return
    }
    if (fmt.needsReport && !reportA) {
      setError('Run simulation first to export CSV data.')
      return
    }
    let content: string
    try {
      content = fmt.generate()
    } catch (err) {
      setError(`Export failed: ${err instanceof Error ? err.message : String(err)}`)
      return
    }
    await saveText(fmt.ext, fmt.fileName?.() ?? `${baseName}.${fmt.ext}`, content)
  }

  async function exportPDFReport() {
    if (!reportA) { setError('Run simulation first to export the PDF report.'); return }
    const html = buildPDFHtml(graph, reportA, verdictReport)
    if (platform.name === 'web') {
      printHtml(html)
      setError(null)
      setStatus('Print dialog opened — choose "Save as PDF".')
    } else {
      // Desktop WebView neumí spolehlivě otevřít tiskové okno (window.open
      // + document.write v Tauri nefungovalo) — report se uloží jako HTML,
      // které jde otevřít v prohlížeči a vytisknout do PDF.
      await saveText('html', `${baseName}_report.html`, html)
    }
  }

  async function exportWebShare() {
    // Přes platformní uložení — blob <a download> v desktopové WebView nefunguje.
    await saveText('html', `${baseName}_share.html`, buildWebShareHtml(graph, reportA))
  }

  return (
    <div className="flex flex-col gap-4 max-w-lg">
      <h2 className="text-sm font-semibold text-white/80">Export</h2>

      {/* PDF + Web Share row */}
      <div className="flex gap-2">
        <button
          onClick={exportPDFReport}
          disabled={!isPro}
          title={!isPro ? 'Requires GSS PRO' : platform.name === 'web' ? 'Print the simulation report (save as PDF)' : 'Save a print-ready HTML report (open it in a browser and print to PDF)'}
          className="flex-1 flex items-center justify-between p-3 bg-card border border-border rounded-lg disabled:opacity-40 disabled:cursor-not-allowed hover:border-white/20 transition-colors"
        >
          <div className="flex items-center gap-2">
            <span className="text-xs text-white">📄 PDF Report</span>
            <span className="px-1.5 py-0.5 bg-accent/20 text-accent text-[9px] rounded font-semibold">PRO</span>
          </div>
          <span className="text-xs text-white/50">{!isPro ? '🔒' : '↓'}</span>
        </button>
        <button
          onClick={exportWebShare}
          disabled={!isPro}
          title={!isPro ? 'Requires GSS PRO' : 'Export as shareable standalone HTML'}
          className="flex-1 flex items-center justify-between p-3 bg-card border border-border rounded-lg disabled:opacity-40 disabled:cursor-not-allowed hover:border-white/20 transition-colors"
        >
          <div className="flex items-center gap-2">
            <span className="text-xs text-white">🌐 Web Share</span>
            <span className="px-1.5 py-0.5 bg-accent/20 text-accent text-[9px] rounded font-semibold">PRO</span>
          </div>
          <span className="text-xs text-white/50">{!isPro ? '🔒' : '↓'}</span>
        </button>
      </div>

      <div className="flex flex-col gap-2">
        {formats.map((fmt) => {
          const locked = fmt.pro && !isPro
          return (
            <div
              key={fmt.id}
              className="flex items-center justify-between p-3 bg-card border border-border rounded-lg"
            >
              <div className="flex items-center gap-2">
                <span className="text-xs text-white">{fmt.label}</span>
                {fmt.pro && (
                  <span className="px-1.5 py-0.5 bg-accent/20 text-accent text-[9px] rounded font-semibold">
                    PRO
                  </span>
                )}
              </div>
              <button
                onClick={() => handleExport(fmt)}
                disabled={locked}
                className="px-3 py-1.5 text-xs rounded transition-colors disabled:opacity-40 disabled:cursor-not-allowed bg-border hover:bg-border/70 text-white"
              >
                {locked ? '🔒 Upgrade' : 'Export'}
              </button>
            </div>
          )
        })}
      </div>

      {status && (
        <div className="p-2 bg-green-400/10 border border-green-400/20 rounded text-green-400 text-xs">
          ✓ {status}
        </div>
      )}
      {error && (
        <div className="p-2 bg-red-400/10 border border-red-400/20 rounded text-red-400 text-xs">
          {error}
        </div>
      )}
    </div>
  )
}
