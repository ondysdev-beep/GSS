// TypeScript / Web exporter (PRO) — typed interfaces + immutable config objekty pro všechny typy uzlů.

import type { GSSGraph } from '../../types/graph'
import { NodeType } from '../../types/graph'
import { APP_VERSION } from '../version'
import {
  GATE_OPERATORS, commentText, dataOf, identifier, nodeIdentifiers, nodesOfType, num, quote, splitterWeights, str,
} from './common'

export function exportTypeScript(
  graph: GSSGraph,
): string {
  const CONST = identifier(String(graph.name ?? ''), 'ECONOMY_CONFIG').toUpperCase()
  const ids = nodeIdentifiers(graph)
  const ts = new Date().toISOString()
  const n0 = (v: unknown, fallback: number) => String(num(v, fallback))

  const L: string[] = []

  L.push(`// Generated by GSS v${APP_VERSION} (graph format ${commentText(graph.version)}) — Game Systems Simulator`)
  L.push(`// Graph: ${commentText(graph.name)}  |  Generated: ${ts}`)
  L.push(`// PRO export — TypeScript / Web / Node.js`)
  L.push('')

  // Interfaces
  L.push('// ——— Interfaces ———')
  const iface = (name: string, fields: string[]) => {
    L.push(`export interface ${name} {`)
    for (const f of fields) L.push(`  readonly ${f}`)
    L.push('}')
    L.push('')
  }
  iface('GSSPoolConfig', ['id: string', 'resource: string', 'capacity: number', 'initialAmount: number'])
  iface('GSSSourceConfig', ['id: string', 'resource: string', 'rate: number'])
  iface('GSSConverterConfig', ['id: string', 'inputResource: string', 'inputAmount: number', 'outputResource: string', 'outputAmount: number', 'cycleTime: number'])
  iface('GSSDrainConfig', ['id: string', 'resource: string', 'rate: number'])
  iface('GSSGateConfig', ['id: string', 'variable: string', "operator: '>' | '>=' | '<' | '<=' | '==' | '!='", 'threshold: number'])
  iface('GSSChanceConfig', ['id: string', 'successChance: number'])
  iface('GSSSplitterConfig', ['id: string', 'weighted: boolean', 'outputCount: number', 'weights: readonly number[]'])
  iface('GSSTimerConfig', ['id: string', 'resource: string', 'amount: number', 'interval: number'])
  iface('GSSFormulaConfig', ['id: string', 'expression: string', 'outputResource: string'])
  iface('GSSPlayerActionConfig', ['id: string', 'resource: string', 'amount: number', 'cadence: number'])
  iface('GSSConnectionConfig', ['fromNode: string', 'toNode: string', 'fromPort: number  // Chance: 0 = success, 1 = failure'])
  iface('GSSEconomyConfig', [
    'name: string', 'version: string',
    'pools: readonly GSSPoolConfig[]', 'sources: readonly GSSSourceConfig[]',
    'converters: readonly GSSConverterConfig[]', 'drains: readonly GSSDrainConfig[]',
    'gates: readonly GSSGateConfig[]', 'chances: readonly GSSChanceConfig[]',
    'splitters: readonly GSSSplitterConfig[]', 'timers: readonly GSSTimerConfig[]',
    'formulas: readonly GSSFormulaConfig[]', 'playerActions: readonly GSSPlayerActionConfig[]',
    'connections: readonly GSSConnectionConfig[]',
  ])

  // Data
  L.push('// ——— Config data ———')
  L.push(`export const ${CONST}: GSSEconomyConfig = {`)
  L.push(`  name: ${quote(graph.name)},`)
  L.push(`  version: ${quote(graph.version)},`)
  const list = (field: string, items: string[]) => {
    L.push(`  ${field}: [`)
    for (const it of items) L.push(`    ${it},`)
    L.push('  ],')
  }
  list('pools', nodesOfType(graph, NodeType.POOL).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, resource: ${quote(str(d.resource))}, capacity: ${n0(d.capacity, 100)}, initialAmount: ${n0(d.initial_amount, 0)} }`
  }))
  list('sources', nodesOfType(graph, NodeType.SOURCE).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, resource: ${quote(str(d.resource))}, rate: ${n0(d.rate, 1)} }`
  }))
  list('converters', nodesOfType(graph, NodeType.CONVERTER).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, inputResource: ${quote(str(d.input_resource))}, inputAmount: ${n0(d.input_amount, 1)}, outputResource: ${quote(str(d.output_resource))}, outputAmount: ${n0(d.output_amount, 1)}, cycleTime: ${n0(d.cycle_time, 1)} }`
  }))
  list('drains', nodesOfType(graph, NodeType.DRAIN).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, resource: ${quote(str(d.resource))}, rate: ${n0(d.rate, 1)} }`
  }))
  list('gates', nodesOfType(graph, NodeType.GATE).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, variable: ${quote(str(d.variable))}, operator: ${quote(GATE_OPERATORS[num(d.operator, 0)] ?? '>')}, threshold: ${n0(d.value, 0)} }`
  }))
  list('chances', nodesOfType(graph, NodeType.CHANCE).map((n) =>
    `{ id: ${quote(n.id)}, successChance: ${n0(dataOf(n).success_chance, 50)} }`))
  list('splitters', nodesOfType(graph, NodeType.SPLITTER).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, weighted: ${num(d.split_mode, 0) === 1}, outputCount: ${Math.trunc(num(d.output_count, 2))}, weights: [${splitterWeights(d.weights).join(', ')}] }`
  }))
  list('timers', nodesOfType(graph, NodeType.TIMER).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, resource: ${quote(str(d.resource))}, amount: ${n0(d.amount, 1)}, interval: ${n0(d.interval, 60)} }`
  }))
  list('formulas', nodesOfType(graph, NodeType.FORMULA).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, expression: ${quote(str(d.expression))}, outputResource: ${quote(str(d.output_resource))} }`
  }))
  list('playerActions', nodesOfType(graph, NodeType.PLAYER_ACTION).map((n) => {
    const d = dataOf(n)
    return `{ id: ${quote(n.id)}, resource: ${quote(str(d.resource))}, amount: ${n0(d.amount, 1)}, cadence: ${n0(d.cadence, 5)} }`
  }))
  list('connections', graph.connections.map((c) =>
    `{ fromNode: ${quote(c.from_node)}, toNode: ${quote(c.to_node)}, fromPort: ${Math.trunc(num(c.from_port, 0))} }`))
  L.push('} as const')
  L.push('')

  // Rychlý lookup helper
  L.push('// ——— Helpers for easy lookup ———')
  L.push(`export const POOLS: Record<string, GSSPoolConfig> = Object.fromEntries(${CONST}.pools.map((p) => [p.id, p]))`)
  L.push(`export const SOURCES: Record<string, GSSSourceConfig> = Object.fromEntries(${CONST}.sources.map((s) => [s.id, s]))`)
  L.push('')

  // Individuální named exporty pro každý Pool (unikátní identifikátory)
  const pools = nodesOfType(graph, NodeType.POOL)
  if (pools.length > 0) {
    L.push('// ——— Named pool constants ———')
    for (const n of pools) {
      L.push(`export const POOL_${ids.get(String(n.id))!.toUpperCase()} = POOLS[${quote(n.id)}]`)
    }
    L.push('')
  }

  return L.join('\n')
}
