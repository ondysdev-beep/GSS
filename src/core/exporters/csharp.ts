// C# / Unity exporter (PRO) — typed ScriptableObject with configuration for all node types.
//
// All data types are nested inside the generated class, so several exported
// economies can live in one Unity project without duplicate type names.
// Unity requires the file name to match the class name — use
// csharpClassName() for the file name (ExportPanel does).

import type { GSSGraph } from '../../types/graph'
import { NodeType } from '../../types/graph'
import { APP_VERSION } from '../version'
import {
  GATE_OPERATORS, commentText, dataOf, identifier, nodesOfType, num, quote, splitterWeights, str,
} from './common'

const CSHARP_KEYWORDS = new Set([
  'abstract', 'as', 'base', 'bool', 'break', 'byte', 'case', 'catch', 'char', 'checked', 'class', 'const',
  'continue', 'decimal', 'default', 'delegate', 'do', 'double', 'else', 'enum', 'event', 'explicit', 'extern',
  'false', 'finally', 'fixed', 'float', 'for', 'foreach', 'goto', 'if', 'implicit', 'in', 'int', 'interface',
  'internal', 'is', 'lock', 'long', 'namespace', 'new', 'null', 'object', 'operator', 'out', 'override',
  'params', 'private', 'protected', 'public', 'readonly', 'ref', 'return', 'sbyte', 'sealed', 'short',
  'sizeof', 'stackalloc', 'static', 'string', 'struct', 'switch', 'this', 'throw', 'true', 'try', 'typeof',
  'uint', 'ulong', 'unchecked', 'unsafe', 'ushort', 'using', 'virtual', 'void', 'volatile', 'while',
])

/** Class (and file) name for the exported ScriptableObject. */
export function csharpClassName(graph: GSSGraph): string {
  // PascalCase z názvu grafu; nesmí začínat číslicí ani být klíčové slovo.
  const pascal = String(graph.name ?? '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
  const id = identifier(pascal, 'EconomyConfig')
  return CSHARP_KEYWORDS.has(id) ? `${id}Config` : id
}

/** float literal — always with the `f` suffix (a bare 1e+21 would be a double). */
function f(v: number): string {
  return `${v}f`
}

function int(v: number): string {
  return String(Math.trunc(v))
}

export function exportCSharp(
  graph: GSSGraph,
): string {
  const cls = csharpClassName(graph)
  const ts  = new Date().toISOString()
  const L: string[] = []

  L.push(`// Generated by GSS v${APP_VERSION} (graph format ${commentText(graph.version)}) — Game Systems Simulator`)
  L.push(`// Graph: ${commentText(graph.name)}  |  Generated: ${ts}`)
  L.push('// PRO export — C# / Unity. Save this file as ' + `${cls}.cs` + ' (Unity requires matching names).')
  L.push('')
  L.push('using System;')
  L.push('using UnityEngine;')
  L.push('')
  L.push('/// <summary>')
  L.push(`/// Economy configuration: ${commentText(graph.name).replace(/[<>&]/g, '')}`)
  L.push(`/// Create an asset via Assets → Create → GSS → ${cls}`)
  L.push('/// </summary>')
  L.push(`[CreateAssetMenu(fileName = ${quote(cls)}, menuName = ${quote(`GSS/${cls}`)})]`)
  L.push(`public class ${cls} : ScriptableObject`)
  L.push('{')

  // ---- Nested data types ----
  const struct = (name: string, fields: string[]) => {
    L.push('    [Serializable]')
    L.push(`    public struct ${name}`)
    L.push('    {')
    for (const fld of fields) L.push(`        public ${fld};`)
    L.push('    }')
    L.push('')
  }
  struct('Pool', ['string id', 'string resource', 'float capacity', 'float initialAmount'])
  struct('Source', ['string id', 'string resource', 'float rate'])
  struct('Converter', ['string id', 'string inputResource', 'float inputAmount', 'string outputResource', 'float outputAmount', 'float cycleTime'])
  struct('Drain', ['string id', 'string resource', 'float rate'])
  struct('Gate', ['string id', 'string variable', 'string op', 'float threshold'])
  struct('Chance', ['string id', 'float successChance'])
  struct('Splitter', ['string id', 'bool weighted', 'int outputCount', 'float[] weights'])
  struct('Timer', ['string id', 'string resource', 'float amount', 'float interval'])
  struct('Formula', ['string id', 'string expression', 'string outputResource'])
  struct('PlayerAction', ['string id', 'string resource', 'float amount', 'float cadence'])
  struct('Connection', ['string fromNode', 'string toNode', 'int fromPort'])

  // ---- Data arrays ----
  const array = (header: string, typeName: string, field: string, items: string[]) => {
    L.push(`    [Header(${quote(header)})]`)
    L.push(`    public ${typeName}[] ${field} = new ${typeName}[]`)
    L.push('    {')
    for (const it of items) L.push(`        ${it},`)
    L.push('    };')
    L.push('')
  }

  array('Pools', 'Pool', 'pools', nodesOfType(graph, NodeType.POOL).map((n) => {
    const d = dataOf(n)
    return `new Pool { id = ${quote(n.id)}, resource = ${quote(str(d.resource))}, capacity = ${f(num(d.capacity, 100))}, initialAmount = ${f(num(d.initial_amount, 0))} }`
  }))
  array('Sources', 'Source', 'sources', nodesOfType(graph, NodeType.SOURCE).map((n) => {
    const d = dataOf(n)
    return `new Source { id = ${quote(n.id)}, resource = ${quote(str(d.resource))}, rate = ${f(num(d.rate, 1))} }`
  }))
  array('Converters', 'Converter', 'converters', nodesOfType(graph, NodeType.CONVERTER).map((n) => {
    const d = dataOf(n)
    return `new Converter { id = ${quote(n.id)}, inputResource = ${quote(str(d.input_resource))}, inputAmount = ${f(num(d.input_amount, 1))}, outputResource = ${quote(str(d.output_resource))}, outputAmount = ${f(num(d.output_amount, 1))}, cycleTime = ${f(num(d.cycle_time, 1))} }`
  }))
  array('Drains', 'Drain', 'drains', nodesOfType(graph, NodeType.DRAIN).map((n) => {
    const d = dataOf(n)
    return `new Drain { id = ${quote(n.id)}, resource = ${quote(str(d.resource))}, rate = ${f(num(d.rate, 1))} }`
  }))
  array('Gates', 'Gate', 'gates', nodesOfType(graph, NodeType.GATE).map((n) => {
    const d = dataOf(n)
    const op = GATE_OPERATORS[num(d.operator, 0)] ?? '>'
    return `new Gate { id = ${quote(n.id)}, variable = ${quote(str(d.variable))}, op = ${quote(op)}, threshold = ${f(num(d.value, 0))} }`
  }))
  array('Chance Nodes', 'Chance', 'chances', nodesOfType(graph, NodeType.CHANCE).map((n) =>
    `new Chance { id = ${quote(n.id)}, successChance = ${f(num(dataOf(n).success_chance, 50))} }`))
  array('Splitters', 'Splitter', 'splitters', nodesOfType(graph, NodeType.SPLITTER).map((n) => {
    const d = dataOf(n)
    const weights = splitterWeights(d.weights).map(f).join(', ')
    return `new Splitter { id = ${quote(n.id)}, weighted = ${num(d.split_mode, 0) === 1 ? 'true' : 'false'}, outputCount = ${int(num(d.output_count, 2))}, weights = new float[] { ${weights} } }`
  }))
  array('Timers', 'Timer', 'timers', nodesOfType(graph, NodeType.TIMER).map((n) => {
    const d = dataOf(n)
    return `new Timer { id = ${quote(n.id)}, resource = ${quote(str(d.resource))}, amount = ${f(num(d.amount, 1))}, interval = ${f(num(d.interval, 60))} }`
  }))
  array('Formulas (evaluate per tick: resource totals + tick)', 'Formula', 'formulas', nodesOfType(graph, NodeType.FORMULA).map((n) => {
    const d = dataOf(n)
    return `new Formula { id = ${quote(n.id)}, expression = ${quote(str(d.expression))}, outputResource = ${quote(str(d.output_resource))} }`
  }))
  array('Player Actions', 'PlayerAction', 'playerActions', nodesOfType(graph, NodeType.PLAYER_ACTION).map((n) => {
    const d = dataOf(n)
    return `new PlayerAction { id = ${quote(n.id)}, resource = ${quote(str(d.resource))}, amount = ${f(num(d.amount, 1))}, cadence = ${f(num(d.cadence, 5))} }`
  }))
  array('Connections (fromPort: Chance 0 = success, 1 = failure)', 'Connection', 'connections', graph.connections.map((c) =>
    `new Connection { fromNode = ${quote(c.from_node)}, toNode = ${quote(c.to_node)}, fromPort = ${int(num(c.from_port, 0))} }`))

  L.push('}')
  L.push('')
  return L.join('\n')
}
