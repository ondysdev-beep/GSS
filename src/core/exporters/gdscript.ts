// GDScript / Godot 4 exporter (PRO) — typed Resource s @export anotacemi pro všechny typy uzlů.

import type { GSSGraph, GSSNode } from '../../types/graph'
import { NodeType } from '../../types/graph'
import { APP_VERSION } from '../version'
import {
  GATE_OPERATORS, commentText, dataOf, identifier, nodeIdentifiers, nodesOfType, num, quote, splitterWeights, str,
} from './common'

/** class_name for the exported Resource. The "GSS" prefix keeps it clear of Godot's built-in classes (Resource, Timer…). */
export function gdscriptClassName(graph: GSSGraph): string {
  const pascal = String(graph.name ?? '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
  return `GSS${identifier(pascal, 'Economy')}`
}

/** float literal (GDScript accepts ints for float vars, but `.0` keeps intent explicit). */
function fl(v: number): string {
  const s = String(v)
  return /^-?\d+$/.test(s) ? `${s}.0` : s
}

export function exportGDScript(
  graph: GSSGraph,
): string {
  const className = gdscriptClassName(graph)
  const ids = nodeIdentifiers(graph)
  const ts = new Date().toISOString()
  const L: string[] = []

  L.push(`# Generated by GSS v${APP_VERSION} (graph format ${commentText(graph.version)}) — Game Systems Simulator`)
  L.push(`# Graph: ${commentText(graph.name)}  |  Generated: ${ts}`)
  L.push(`# PRO export — GDScript / Godot 4`)
  L.push('')
  L.push(`class_name ${className}`)
  L.push('extends Resource')
  L.push('')

  const section = (title: string, type: number, emit: (n: GSSNode, v: string, d: Record<string, unknown>) => string[]) => {
    const nodes = nodesOfType(graph, type)
    if (nodes.length === 0) return
    L.push(`# — ${title} —`)
    for (const n of nodes) {
      L.push(`@export_group(${quote(`${title.replace(/s$/, '')}: ${n.label ?? n.id}`)})`)
      for (const line of emit(n, ids.get(String(n.id))!, dataOf(n))) L.push(line)
      L.push('')
    }
  }

  section('Pools', NodeType.POOL, (_n, v, d) => [
    `@export var ${v}_resource: String = ${quote(str(d.resource))}`,
    `@export var ${v}_capacity: float = ${fl(num(d.capacity, 100))}`,
    `@export var ${v}_initial: float = ${fl(num(d.initial_amount, 0))}`,
  ])
  section('Sources', NodeType.SOURCE, (_n, v, d) => [
    `@export var ${v}_resource: String = ${quote(str(d.resource))}`,
    `@export var ${v}_rate: float = ${fl(num(d.rate, 1))}`,
  ])
  section('Converters', NodeType.CONVERTER, (_n, v, d) => [
    `@export var ${v}_in_resource: String = ${quote(str(d.input_resource))}`,
    `@export var ${v}_in_amount: float = ${fl(num(d.input_amount, 1))}`,
    `@export var ${v}_out_resource: String = ${quote(str(d.output_resource))}`,
    `@export var ${v}_out_amount: float = ${fl(num(d.output_amount, 1))}`,
    `@export var ${v}_cycle_time: float = ${fl(num(d.cycle_time, 1))}`,
  ])
  section('Drains', NodeType.DRAIN, (_n, v, d) => [
    `@export var ${v}_resource: String = ${quote(str(d.resource))}`,
    `@export var ${v}_rate: float = ${fl(num(d.rate, 1))}`,
  ])
  section('Gates', NodeType.GATE, (_n, v, d) => [
    `@export var ${v}_variable: String = ${quote(str(d.variable))}`,
    `@export var ${v}_operator: String = ${quote(GATE_OPERATORS[num(d.operator, 0)] ?? '>')}`,
    `@export var ${v}_threshold: float = ${fl(num(d.value, 0))}`,
  ])
  section('Chance nodes', NodeType.CHANCE, (_n, v, d) => [
    `@export_range(0, 100) var ${v}_success_chance: float = ${fl(num(d.success_chance, 50))}`,
  ])
  section('Splitters', NodeType.SPLITTER, (_n, v, d) => [
    `@export_enum("Equal", "Weighted") var ${v}_mode: int = ${num(d.split_mode, 0) === 1 ? 1 : 0}`,
    `@export var ${v}_outputs: int = ${Math.trunc(num(d.output_count, 2))}`,
    `@export var ${v}_weights: PackedFloat32Array = PackedFloat32Array([${splitterWeights(d.weights).map(fl).join(', ')}])`,
  ])
  section('Timers', NodeType.TIMER, (_n, v, d) => [
    `@export var ${v}_resource: String = ${quote(str(d.resource))}`,
    `@export var ${v}_amount: float = ${fl(num(d.amount, 1))}`,
    `@export var ${v}_interval: float = ${fl(num(d.interval, 60))}`,
  ])
  section('Formulas', NodeType.FORMULA, (_n, v, d) => [
    `@export var ${v}_expression: String = ${quote(str(d.expression))}`,
    `@export var ${v}_output_resource: String = ${quote(str(d.output_resource))}`,
  ])
  section('Player Actions', NodeType.PLAYER_ACTION, (_n, v, d) => [
    `@export var ${v}_resource: String = ${quote(str(d.resource))}`,
    `@export var ${v}_amount: float = ${fl(num(d.amount, 1))}`,
    `@export var ${v}_cadence: float = ${fl(num(d.cadence, 5))}`,
  ])

  // Connections jako Dictionary array (port: Chance 0 = success, 1 = failure)
  if (graph.connections.length > 0) {
    L.push('# — Connections —')
    L.push('@export var connections: Array[Dictionary] = [')
    for (const c of graph.connections) {
      L.push(`\t{ "from": ${quote(c.from_node)}, "to": ${quote(c.to_node)}, "port": ${Math.trunc(num(c.from_port, 0))} },`)
    }
    L.push(']')
    L.push('')
  }

  return L.join('\n')
}
